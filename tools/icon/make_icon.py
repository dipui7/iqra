#!/usr/bin/env python3
"""
Draw the app icon (an open book on green) and write every form the builds need:

  composeApp/src/androidMain/res/drawable/ic_launcher_foreground.xml   Android adaptive icon (book)
  composeApp/src/commonMain/composeResources/drawable/app_icon.xml     desktop window icon
  composeApp/icon.ico, composeApp/icon.png                             Windows installer / Linux

Needs Pillow (pip install pillow). Edit the shapes below and re-run to change the icon.
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GREEN = "#2E8B62"
GREEN_DARK = "#236E4D"
# Android masks adaptive icons to the middle of the canvas; standalone icons can fill more of it.
STANDALONE_SCALE = 1.35
CENTER = (54, 55)

# Shapes on a 108 x 108 canvas (Android adaptive icon size; the middle 66 x 66 is always visible).
# Each page: start point, then cubic curves / lines, as (kind, points...).
LEFT_PAGE = [("M", (52.5, 41)), ("C", (45, 36.5), (36, 35.5), (29, 37.5)), ("L", (29, 70)),
             ("C", (36, 68), (45, 69), (52.5, 73.5)), ("Z",)]
RIGHT_PAGE = [("M", (55.5, 41)), ("C", (63, 36.5), (72, 35.5), (79, 37.5)), ("L", (79, 70)),
              ("C", (72, 68), (63, 69), (55.5, 73.5)), ("Z",)]
# Lines of "text" on the pages.
LINES = [[("M", (34, 45)), ("C", (39, 44), (44, 44.5), (48, 46.5))],
         [("M", (34, 51)), ("C", (39, 50), (44, 50.5), (48, 52.5))],
         [("M", (34, 57)), ("C", (39, 56), (44, 56.5), (48, 58.5))],
         [("M", (74, 45)), ("C", (69, 44), (64, 44.5), (60, 46.5))],
         [("M", (74, 51)), ("C", (69, 50), (64, 50.5), (60, 52.5))],
         [("M", (74, 57)), ("C", (69, 56), (64, 56.5), (60, 58.5))]]


def path_data(cmds):
    out = []
    for c in cmds:
        out.append(c[0] + " ".join(f"{x:g},{y:g}" for x, y in c[1:]))
    return " ".join(out)


def vector(background):
    bg = (f'    <path android:fillColor="{GREEN}" android:pathData="M24,0 H84 A24,24 0 0 1 108,24 V84 '
          f'A24,24 0 0 1 84,108 H24 A24,24 0 0 1 0,84 V24 A24,24 0 0 1 24,0 Z" />\n') if background else ""
    group = (f'    <group android:scaleX="{STANDALONE_SCALE}" android:scaleY="{STANDALONE_SCALE}" '
             f'android:pivotX="{CENTER[0]}" android:pivotY="{CENTER[1]}">\n') if background else ""
    pages = "".join(f'    <path android:fillColor="#FFFFFF" android:pathData="{path_data(p)}" />\n'
                    for p in (LEFT_PAGE, RIGHT_PAGE))
    lines = "".join(f'    <path android:strokeColor="{GREEN_DARK}" android:strokeWidth="1.6" '
                    f'android:strokeLineCap="round" android:pathData="{path_data(l)}" />\n' for l in LINES)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/icon/make_icon.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'{bg}{group}{pages}{lines}{"    </group>" + chr(10) if background else ""}</vector>\n')


def polyline(cmds, scale):
    pts, cur = [], None
    for c in cmds:
        if c[0] in "ML":
            cur = c[1]
            pts.append(cur)
        elif c[0] == "C":
            p0, (p1, p2, p3) = cur, c[1:]
            for i in range(1, 25):
                t = i / 24
                x = (1-t)**3*p0[0] + 3*(1-t)**2*t*p1[0] + 3*(1-t)*t*t*p2[0] + t**3*p3[0]
                y = (1-t)**3*p0[1] + 3*(1-t)**2*t*p1[1] + 3*(1-t)*t*t*p2[1] + t**3*p3[1]
                pts.append((x, y))
            cur = p3
    k, (cx, cy) = STANDALONE_SCALE, CENTER
    return [((cx + (x - cx) * k) * scale, (cy + (y - cy) * k) * scale) for x, y in pts]


def raster(size):
    from PIL import Image, ImageDraw
    big = size * 4  # draw large, then downsample for smooth edges
    s = big / 108
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, big - 1, big - 1), radius=24 * s, fill=GREEN)
    for page in (LEFT_PAGE, RIGHT_PAGE):
        d.polygon(polyline(page, s), fill="white")
    for line in LINES:
        d.line(polyline(line, s), fill=GREEN_DARK, width=max(1, round(1.6 * STANDALONE_SCALE * s)), joint="curve")
    return img.resize((size, size), Image.LANCZOS)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", rel)


if __name__ == "__main__":
    write("composeApp/src/androidMain/res/drawable/ic_launcher_foreground.xml", vector(background=False))
    write("composeApp/src/commonMain/composeResources/drawable/app_icon.xml", vector(background=True))
    img = raster(512)
    img.save(os.path.join(ROOT, "composeApp/icon.png"))
    img.save(os.path.join(ROOT, "composeApp/icon.ico"), sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("wrote composeApp/icon.png, composeApp/icon.ico")
